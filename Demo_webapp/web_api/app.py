# 6. SEQUENCE DOWNLOAD -- one bioactivity's peptide sequences, on demand (05_Dashboard.py)
# -----------------------------------------------------------------------------------------
@app.get("/jobs/{job_uuid}/download")
def download_sequence_file(
    job_uuid: str,
    group: str = Query(..., description='e.g. "Group 1", "Group 3a"'),
    bioactivity: str = Query(..., description='e.g. "ACE_inhibitor" -- the raw name, matching the CSV filename'),
    authorization: Optional[str] = Header(None),
):
    """
    On-demand counterpart to GET /jobs/{job_uuid}/result: returns the real peptide-sequence CSV for
    exactly the one group + bioactivity the user clicked "Download" for,
    """
    if not authorization:
        raise HTTPException(status_code=401, detail="Missing Token")

    row = db.get_job_by_uuid(job_uuid)
    if row is None:
        raise HTTPException(status_code=404, detail="Job not found")

    output_path = row["output_result_path"]
    if not output_path:
        raise HTTPException(
            status_code=409,
            detail="Job results are not ready yet. Wait for status to reach SUCCESS before requesting a download.",
        )

    job_output_dir = Path(output_path).resolve()
    if not job_output_dir.is_dir():
        raise HTTPException(status_code=500, detail=f"output_result_path does not exist on disk: {output_path}")

    # "Group 1" -> "G1" -> the ResultG1/ subfolder this job's sequence files live under.
    group_id = group.replace("Group ", "G")
    candidate = (job_output_dir / f"Result{group_id}" / f"{bioactivity}.csv").resolve()
    # Defend against path traversal via the group/bioactivity query params
    # (e.g. bioactivity="../../etc/passwd") -- reject anything that would
    # resolve outside job_output_dir before touching the filesystem.
    if job_output_dir not in candidate.parents:
        raise HTTPException(status_code=400, detail="Invalid group or bioactivity value")
    if not candidate.is_file():
        raise HTTPException(status_code=404, detail=f"No sequence file for group={group}, bioactivity={bioactivity}")

    return Response(content=candidate.read_text(encoding="utf-8-sig"), media_type="text/csv")

