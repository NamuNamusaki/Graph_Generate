# 5. JOB RESULT -- statistics only (05_Dashboard.py)
# -----------------------------------------------------------------------------------------
@app.get("/jobs/{job_uuid}/result")
def get_job_result(job_uuid: str, authorization: Optional[str] = Header(None)):
    """
    Statistical summary for the Dashboard's charts/tables: job status/error
    plus the 4 RankBioactivity_G*_2Enz.csv files. Does NOT include peptide
    sequence data -- that's fetched on demand, one bioactivity at a time,
    via GET /jobs/{job_uuid}/download when the user actually clicks a
    "Download CSV" button. Eagerly reading every sequence file on every
    dashboard visit doesn't scale once a real job's ResultG*/ folders hold
    more than this repo's handful of sample files, and most of them are
    never even looked at in a given visit.

    Returns:
      - job_id, status, error_message: current job state. error_message is
        always present (None unless the job failed) so the frontend has one
        place to check instead of parsing HTTP status codes for it.
      - stat_files: {group_label: [{"Bioactivity", "nPepSeq"}, ...]}, read
        from this job's RankBioactivity_G*_2Enz.csv files.

    stat_files is empty ({}) until the job actually reaches SUCCESS (i.e.
    output_result_path is set) -- the frontend should treat that the same
    way it used to treat the old endpoint's 409: "still processing," not an
    error. authorization/existence problems (missing token, unknown job,
    corrupt result files) still raise real HTTP errors, since those are
    protocol-level failures, not job states.
    """
    if not authorization:
        raise HTTPException(status_code=401, detail="Missing Token")

    row = db.get_job_by_uuid(job_uuid)
    if row is None:
        raise HTTPException(status_code=404, detail="Job not found")

    output_path = row["output_result_path"]
    stat_files: Dict[str, list] = {}

    if output_path:
        job_output_dir = Path(output_path).resolve()
        if not job_output_dir.is_dir():
            raise HTTPException(status_code=500, detail=f"output_result_path does not exist on disk: {output_path}")

        # Stat files: RankBioactivity_G*_2Enz.csv (columns: Bioactivity, nPepSeq)
        for path in sorted(job_output_dir.glob("RankBioactivity_*.csv")):
            group_label = _group_label_from_filename(path.stem)
            if group_label is None:
                continue  # skip anything that doesn't match the expected naming pattern

            # encoding="utf-8-sig" strips the leading BOM these files were saved with
            # (otherwise the first column reads as "﻿Bioactivity", not "Bioactivity")
            df = pd.read_csv(path, encoding="utf-8-sig")
            missing = {"Bioactivity", "nPepSeq"} - set(df.columns)
            if missing:
                raise HTTPException(status_code=500, detail=f"{path.name} is missing columns: {sorted(missing)}")
            stat_files[group_label] = df.to_dict(orient="records")

    return {
        "job_id": _format_job_id(row["id"]),
        "status": row["status"],
        "error_message": row["error_message"],
        "stat_files": stat_files,
    }

