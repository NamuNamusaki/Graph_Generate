# 2. UPLOAD & SUBMISSION (03_Data_prep.py)
# -----------------------------------------------------------------------------------------
class AnalyzePayload(BaseModel):
    project_name: str
    sample_name: Optional[str] = None
    list_bioactivities_id: list[int]
    fasta_content: str
    # Catch any other fields dynamically
    model_config = {"extra": "allow"}

@app.post("/jobs")
def submit_analysis(payload: AnalyzePayload, authorization: Optional[str] = Header(None)):
    if not authorization:
        raise HTTPException(status_code=401, detail="Missing Token")

    # ──── GENERATE job_uuid ──────────────────────────────────────
    job_uuid = str(uuid.uuid4())

    user_id = _get_or_create_demo_user()

    # Every submission becomes its own PROJECTS row -- the frontend has no
    # separate "create a project" step distinct from submitting a job, so a
    # fresh project per submission mirrors how it's actually used today.
    extra_fields = payload.model_dump()
    project_id = db.create_project(
        user_id,
        project_name=payload.project_name,
        description=extra_fields.get("description"),
    )

    # input_fasta_path stays null: the raw sequence text is sent inline in
    # this request rather than written to a file first (see the matching
    # note in schema.sql's header) -- a real worker would write it to disk
    # and this column would point at that file.
    db.create_job(
        job_uuid,
        project_id,
        input_fasta_path=None,
        list_bioactivity_id=payload.list_bioactivities_id,
        list_step_total=PIPELINE_STEPS,
    )
    # create_job() always inserts with status='PENDING' (schema.sql's
    # default) -- immediately advance it to RUNNING so behavior matches
    # what this endpoint always returned: a job that's already underway by
    # the time the frontend gets its response back.
    db.update_job_progress(job_uuid, status="RUNNING", started_at_now=True)

    row = db.get_job_by_uuid(job_uuid)
    job_id = _format_job_id(row["id"])
    return {"job_id": job_id, "job_uuid": job_uuid, "message": "Job started"}

