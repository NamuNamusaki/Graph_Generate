# -----------------------------------------------------------------------------------------
# JOB TRACKING -- backed by MySQL via db.py (users / projects / jobs tables in schema.sql)
# -----------------------------------------------------------------------------------------
# job_id vs. job_uuid — two distinct identifiers, mirroring JOBS in the ERD:
#   - job_uuid: generated by the backend (submit_analysis(), below) when
#     the job is created, and returned once in the POST /jobs response.
#     From then on it's the identifier every API call uses (status polling,
#     results, notifications) -- it's what the wire protocol is keyed on,
#     and the UNIQUE column db.py's create_job()/get_job_by_uuid() actually
#     look jobs up by. The frontend never invents this value; it only ever
#     echoes back whatever the backend handed it.
#   - job_id: a display-friendly label derived from the job row's real
#     MySQL auto-increment primary key (`JOB{id:06d}`, see
#     _format_job_id() below) -- returned so the frontend can use it for
#     its own project tracking / "which of my submissions is this" UI
#     (session state key, project switcher label), but it is never used to
#     address an API call.
PIPELINE_STEPS = ["Reading Data", "In silico Digestion", "Bioactivity Matching", "Generating Results"]

# Email-notification bookkeeping (which address was subscribed, whether the
# completion email already fired, the resulting result_url) is deliberately
# NOT stored in MySQL -- schema.sql's JOBS table (matching the ERD) has no
# columns for it; a real system would model this as its own
# notifications/subscriptions table rather than bolting extra columns onto
# JOBS. Kept here as a small in-memory side-store instead, keyed by
# job_uuid. This means a subscribed email is forgotten if the api container
# restarts mid-job -- unlike job status/results, which now survive restarts
# via MySQL.
job_notifications: Dict[str, dict] = {}


def _format_job_id(db_id: int) -> str:
    """Turns a job row's real MySQL auto-increment id into the same
    'JOB000001'-style label this API always returned, back when job_id came
    from an in-memory counter instead of a real primary key."""
    return f"JOB{db_id:06d}"


# ---------- Demo user (stand-in until login is real) ---------------------------------------
# login() below is still a single hardcoded credential pair -- not real
# authentication, a separately tracked gap. That means there's exactly one
# "user" in the system for now. Every submitted job is attached to this one
# seeded row so PROJECTS/JOBS' foreign keys have a real user_id to point
# at. Swap this out once login actually authenticates against the users
# table and knows which real user is submitting.
_DEMO_USERNAME = "admin"
_DEMO_EMAIL = "admin@smartbiopep.local"


def _get_or_create_demo_user() -> int:
    user = db.get_user_by_username(_DEMO_USERNAME)
    if user is not None:
        return user["id"]
    # password_hash=None -- login() doesn't check this yet, so writing a
    # fake hash here would just be misleading about what's actually secured.
    return db.create_user(_DEMO_USERNAME, _DEMO_EMAIL, password_hash=None)

