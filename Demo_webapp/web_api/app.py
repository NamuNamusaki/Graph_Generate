# 4. MOCK STATUS POLLING (04_Job_status.py)
# -----------------------------------------------------------------------------------------
@app.get("/jobs/{job_uuid}")
def get_status(job_uuid: str, authorization: Optional[str] = Header(None)):
    if not authorization:
        raise HTTPException(status_code=401, detail="Missing Token")

    row = db.get_job_by_uuid(job_uuid)
    if row is None:
        raise HTTPException(status_code=404, detail="Job not found")

    list_step_total = row["list_step_total"] or PIPELINE_STEPS
    step_current = row["step_current"]
    status = row["status"]
    output_result_path = row["output_result_path"]
    already_success = status == "SUCCESS"

    # Simulate progress: Move forward one step every time Streamlit asks
    if step_current < len(list_step_total):
        step_current += 1
        db.update_job_progress(job_uuid, step_current=step_current)

    # If it reaches the end, mark it as SUCCESS and (simulating the worker)
    # write the output_result_path that the frontend should now check for.
    # Guarded by already_success so a job that's already SUCCESS doesn't
    # get its completed_at timestamp re-stamped on every later poll.
    if step_current >= len(list_step_total):
        status = "SUCCESS"
        if not output_result_path:
            output_result_path = _simulate_worker_output_path(job_uuid)
        if not already_success:
            db.update_job_progress(
                job_uuid,
                status=status,
                output_result_path=output_result_path,
                completed_at_now=True,
            )

    # Fire the completion email exactly once, and only if an email was
    # actually subscribed for this job (POST /notifications). Tracked in
    # job_notifications, not the DB row -- see the note near its declaration.
    notif = job_notifications.get(job_uuid, {})
    result_url = notif.get("result_url")
    if notif.get("notify_email") and not notif.get("result_email_sent"):
        result_url = _send_completion_email(notif["notify_email"], job_uuid)
        notif["result_url"] = result_url
        notif["result_email_sent"] = True

    return {
        "job_id": _format_job_id(row["id"]),
        "status": status,
        "step_current": step_current,
        "list_step_total": list_step_total,
        "output_result_path": output_result_path,  # null until SUCCESS
        "result_url": result_url,  # null until the email has gone out
    }

